#!/usr/bin/env node
/**
 * Sync the Monitor Talent naar de Top deck into monitor-sample/.
 *
 * The homepage shows a live fragment of the deck (site.js fetches monitor-sample/index.html,
 * lifts #p02 (Inleiding) and #p05 (het cirkeldiagram) out of it and runs its own pager over
 * them). The deck is built in the monitortalent.nl repo (Vragenlijst-Executive-Search,
 * factsheet-deck/) as a self-contained snapshot per rev. This copies that snapshot here and
 * adds the two pieces the Inleiding figures need outside the deck's own engine:
 *
 *   monitor-sample/p02.js    the figure engine of the Inleiding (stairs, levels, the women
 *                            hopping in from all over the screen), from the deck source
 *   monitor-sample/p02.css   the Inleiding's composition styles, from the deck source
 *
 * Usage:
 *   node scripts/sync-monitor.mjs --from ../Vragenlijst-Executive-Search [--rev c272]
 * Without --rev the rev named in factsheet-deck/deck.json is used.
 */
import { readFileSync, writeFileSync, rmSync, cpSync, existsSync, mkdirSync } from 'node:fs';
import { join, resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const arg = (k) => { const i = process.argv.indexOf(k); return i > -1 ? process.argv[i + 1] : null; };
const from = resolve(arg('--from') || '../Vragenlijst-Executive-Search');
const deckDir = join(from, 'factsheet-deck');
const rev = arg('--rev') || JSON.parse(readFileSync(join(deckDir, 'deck.json'), 'utf8')).rev;
const src = join(from, 'factsheet-cirkel-lab-archive', rev);
const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'monitor-sample');

for (const p of [join(src, 'index.html'), join(deckDir, 'sections', 'p02', 'section.js'), join(deckDir, 'sections', 'p02', 'section.css')]) {
  if (!existsSync(p)) { console.error(`not found: ${p}`); process.exit(1); }
}

// Every adaptation must apply exactly as intended; if the upstream source changed, fail
// loudly instead of shipping a half-adapted file.
function patch(text, file, find, replace) {
  const next = text.replace(find, replace);
  if (next === text) { console.error(`patch did not apply in ${file}: ${find}`); process.exit(1); }
  return next;
}

rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });
for (const f of ['index.html', 'app.js', 'mobile.js', 'cirkel.js', 'cirkelgen-core.js', 'konva.min.js', 'a11y.js', 'a11y-pre.js']) {
  if (existsSync(join(src, f))) cpSync(join(src, f), join(out, f));
}
cpSync(join(src, 'assets'), join(out, 'assets'), { recursive: true });

// The figure engine. Inside the deck the stairs wait for the reader's first wheel tick
// (preRoll) before the figure rises into the card; here the card arrives by the site's own
// snap, so the figure simply enters once the stage is on screen.
let js = readFileSync(join(deckDir, 'sections', 'p02', 'section.js'), 'utf8');
js = patch(js, 'p02.js', "      if (I.preRoll && I.preRoll()) return false;                     // c271 · waiting for the reader's first tick\n", '');
writeFileSync(join(out, 'p02.js'), `/* GENERATED by scripts/sync-monitor.mjs from the deck source (${rev}) — do not edit. */\n` + js);

// The composition styles: the Inleiding part of the section stylesheet (after the shared
// FORM A rules, which style.css carries in its own sizing for the sample).
const css = readFileSync(join(deckDir, 'sections', 'p02', 'section.css'), 'utf8');
const marker = '/* ── p02 inleiding · redesigned composition';
const at = css.indexOf(marker);
if (at < 0) { console.error('p02 composition marker not found in section.css'); process.exit(1); }
writeFileSync(join(out, 'p02.css'), `/* GENERATED by scripts/sync-monitor.mjs from the deck source (${rev}) — do not edit. */\n` + css.slice(at));

writeFileSync(join(out, 'VERSION'), `${rev}\n`);
console.log(`synced monitor ${rev} → monitor-sample/ (+ p02.js, p02.css)`);
